# Guarda un número decimal (float) con el precio unitario
precio = 12.5
# Guarda un número entero (int) con la cantidad de unidades
unidades = 2
# Calcula el total multiplicando 'precio' por 'unidades' y lo guarda en 'total'
total = precio * unidades
# Imprime un texto formateado (f-string) insertando los valores de 'unidades' y 'total'
